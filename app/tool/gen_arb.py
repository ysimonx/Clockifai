def build(lang: str, idx: int) -> dict:
    out: dict = {"@@locale": lang}
    for key in sorted(S):
        v = S[key]
        out[key] = v[idx]
        if len(v) > 2 and idx == 0:
            out[f"@{key}"] = {"placeholders": {p: {"type": t} for p, t in v[2].items()}}
    return out


